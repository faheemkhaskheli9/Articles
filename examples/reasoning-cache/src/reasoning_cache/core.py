"""Small, safe procedural cache for a fixed checkout policy.

The inputs and rules are deliberately constrained. This is an educational
example of procedure reuse, not an implementation of CPU-ARC.
"""
from __future__ import annotations

import ast
import json
import re
from dataclasses import dataclass
from decimal import Decimal, InvalidOperation, ROUND_HALF_UP
from pathlib import Path
from typing import Any

CENT = Decimal('0.01')
LIMIT = Decimal('1000000000000')
FIELDS = ('subtotal', 'discount', 'tax', 'shipping')
PREFIX = re.compile(r'^\s*(?:calculate checkout total|compute total)\s*:\s*', re.I)
FIELD = re.compile(r'\b(subtotal|discount|tax|shipping)\s*[:=]?\s*(\$)?\s*(\d+(?:\.\d{1,2})?)\s*(%)?', re.I)
IDENT = re.compile(r'^[a-z][a-z_0-9]{0,32}$')


class CacheMiss(ValueError):
    """A request is not supported by this cached procedure."""


@dataclass(frozen=True)
class Checkout:
    subtotal: Decimal
    discount: Decimal
    tax: Decimal
    shipping: Decimal

    def variables(self) -> dict[str, Decimal]:
        return {name: getattr(self, name) for name in FIELDS}


def parse_checkout(message: str) -> Checkout:
    """Fail closed on unknown clauses, conflicting fields and unsupported units."""
    prefix = PREFIX.match(message)
    if not prefix:
        raise CacheMiss('Only explicit checkout-total requests are supported')
    remainder = message[prefix.end():]
    values: dict[str, Decimal] = {}
    spans = []
    for match in FIELD.finditer(remainder):
        name, currency, raw, pct = match.groups()
        name = name.lower()
        if name in values:
            raise CacheMiss(f'Duplicate field: {name}')
        if name in ('tax', 'discount') and pct != '%':
            raise CacheMiss(f'{name} must be a percentage')
        if name in ('subtotal', 'shipping') and pct:
            raise CacheMiss(f'{name} cannot be a percentage')
        if currency and name in ('tax', 'discount'):
            raise CacheMiss(f'{name} must not contain a currency symbol')
        values[name] = Decimal(raw)
        spans.append((match.start(), match.end()))

    cursor = 0
    for start, end in spans:
        fragment = remainder[cursor:start]
        if fragment.strip(' \t\r\n,;.'):
            raise CacheMiss('Unsupported policy or extra text')
        cursor = end
    if remainder[cursor:].strip(' \t\r\n,;.'):
        raise CacheMiss('Unsupported policy or extra text')
    if set(values) != set(FIELDS):
        raise CacheMiss('All four fields are required')
    if any(v < 0 for v in values.values()):
        raise CacheMiss('Negative values are unsupported')
    if values['tax'] > 100 or values['discount'] > 100:
        raise CacheMiss('Percentages must be at most 100')
    if any(v > Decimal('10000000') for v in (values['subtotal'], values['shipping'])):
        raise CacheMiss('Amount exceeds demo limit')
    return Checkout(**values)


def money(number: Decimal) -> Decimal:
    return number.quantize(CENT, rounding=ROUND_HALF_UP)


def reference_checkout(order: Checkout) -> dict[str, str]:
    """Independent business-rule reference; not generated by an LLM."""
    discount = money(order.subtotal * order.discount / 100)
    net = money(order.subtotal - discount)
    tax_amount = money(net * order.tax / 100)
    total = money(net + tax_amount + order.shipping)
    return {'discount_amount': str(discount), 'taxable_subtotal': str(net),
            'tax_amount': str(tax_amount), 'total': str(total)}


# The expression interpreter deliberately avoids eval, exec, import, getattr,
# exponentiation, function calls, attribute access, and arbitrary Python syntax.
def evaluate_expr(expression: str, vars_: dict[str, Decimal]) -> Decimal:
    if len(expression) > 160:
        raise ValueError('Expression too long')
    try:
        parsed = ast.parse(expression, mode='eval')
    except SyntaxError as exc:
        raise ValueError('Invalid expression syntax') from exc
    budget = [0]

    def visit(node: ast.AST, depth: int = 0) -> Decimal:
        budget[0] += 1
        if depth > 12 or budget[0] > 48:
            raise ValueError('Expression exceeds complexity budget')
        if isinstance(node, ast.Constant) and type(node.value) in (int, float):
            value = Decimal(str(node.value))
        elif isinstance(node, ast.Name) and node.id in vars_:
            value = vars_[node.id]
        elif isinstance(node, ast.UnaryOp) and isinstance(node.op, (ast.UAdd, ast.USub)):
            n = visit(node.operand, depth + 1)
            value = n if isinstance(node.op, ast.UAdd) else -n
        elif isinstance(node, ast.BinOp) and isinstance(node.op, (ast.Add, ast.Sub, ast.Mult, ast.Div)):
            left, right = visit(node.left, depth + 1), visit(node.right, depth + 1)
            if isinstance(node.op, ast.Add):
                value = left + right
            elif isinstance(node.op, ast.Sub):
                value = left - right
            elif isinstance(node.op, ast.Mult):
                value = left * right
            else:
                if right == 0:
                    raise ValueError('Division by zero')
                value = left / right
        else:
            raise ValueError(f'Disallowed syntax: {node.__class__.__name__}')
        if not value.is_finite() or abs(value) > LIMIT:
            raise ValueError('Intermediate amount out of bounds')
        return value

    try:
        return visit(parsed.body)
    except (InvalidOperation, OverflowError) as exc:
        raise ValueError('Invalid arithmetic') from exc


# Step names are constrained, and each expression may only use earlier steps.
ALLOWED_STEPS = ('discount_amount', 'taxable_subtotal', 'tax_amount', 'total')
CURATED_STEPS = [
    {'name': 'discount_amount', 'expression': 'subtotal * discount / 100'},
    {'name': 'taxable_subtotal', 'expression': 'subtotal - discount_amount'},
    {'name': 'tax_amount', 'expression': 'taxable_subtotal * tax / 100'},
    {'name': 'total', 'expression': 'taxable_subtotal + tax_amount + shipping'},
]


def run_program(steps: list[dict[str, str]], order: Checkout) -> dict[str, str]:
    if len(steps) != len(ALLOWED_STEPS):
        raise ValueError('Expected exactly four steps')
    variables = order.variables()
    result: dict[str, str] = {}
    for spec, expected in zip(steps, ALLOWED_STEPS):
        if not isinstance(spec, dict) or set(spec) != {'name', 'expression'}:
            raise ValueError('Invalid step schema')
        if spec['name'] != expected or not isinstance(spec['expression'], str):
            raise ValueError('Incorrect step name or expression')
        amount = money(evaluate_expr(spec['expression'], variables))
        if amount < 0:
            raise ValueError('Negative output')
        variables[expected] = amount
        result[expected] = str(amount)
    return result


VALIDATION_CASES = (
    Checkout(Decimal('120'), Decimal('10'), Decimal('8'), Decimal('5')),
    Checkout(Decimal('200'), Decimal('15'), Decimal('8'), Decimal('0')),
    Checkout(Decimal('0'), Decimal('0'), Decimal('0'), Decimal('0')),
    Checkout(Decimal('0.05'), Decimal('50'), Decimal('10'), Decimal('1.23')),
    Checkout(Decimal('999.99'), Decimal('100'), Decimal('8.5'), Decimal('7')),
    Checkout(Decimal('1050.37'), Decimal('0'), Decimal('100'), Decimal('0')),
    Checkout(Decimal('10.01'), Decimal('33.33'), Decimal('7.25'), Decimal('4.35')),
)


def validate_steps(steps: list[dict[str, str]]) -> None:
    """Compare candidate outputs against independent reference cases."""
    for case in VALIDATION_CASES:
        if run_program(steps, case) != reference_checkout(case):
            raise ValueError('Candidate failed independent reference tests')


def seed_cache(path: Path) -> None:
    """Seeds a curated procedure, for offline demo and reproducible examples."""
    validate_steps(CURATED_STEPS)
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps({'version': 1, 'procedure': 'checkout-v1',
                               'origin': 'curated', 'steps': CURATED_STEPS}, indent=2), encoding='utf-8')


def load_steps(path: Path) -> list[dict[str, str]] | None:
    if not path.exists():
        return None
    try:
        obj: Any = json.loads(path.read_text(encoding='utf-8'))
        if obj.get('version') != 1 or obj.get('procedure') != 'checkout-v1':
            raise ValueError('Unexpected cache schema')
        steps = obj['steps']
        validate_steps(steps)
        return steps
    except (OSError, ValueError, KeyError, TypeError) as exc:
        raise CacheMiss(f'Invalid cache: {exc}') from exc


def process(message: str, path: Path) -> dict[str, Any]:
    order = parse_checkout(message)
    try:
        steps = load_steps(path)
        if steps is not None:
            result = run_program(steps, order)
            # Defensive comparison for this deliberately narrow example.
            if result != reference_checkout(order):
                raise CacheMiss('Cached output differs from independent reference')
            return {'route': 'cache', 'procedure': 'checkout-v1', 'result': result}
    except (ValueError, CacheMiss):
        pass
    return {'route': 'verified_fallback', 'result': reference_checkout(order)}
